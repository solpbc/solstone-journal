"""Conformance oracle for the active-brain durable record and its fingerprint.

`health/brain.json` is the durable state of the journal's one selected thinking
lane. It is written and validated by `think/providers/brain_state.py`, fenced by
an HMAC fingerprint over the active configuration, and read by the local runtime,
the `brain` CLI, the talent runtime and the provider-readiness surface.

Two different things are pinned here, and only one of them is a vocabulary.

**The vocabularies** are transcribed from the reference module rather than
restated, so a native reader cannot hold its own copy of a closed set. There are
five of them and three carry the same concept under different spellings, which is
exactly why none of them is written down twice.

**The fingerprint algorithm is the hazard.** `canonical_fingerprint` is
`json.dumps(sort_keys=True, separators=(",", ":"), ensure_ascii=True)` over a
recursive normalization, then sha256, then HMAC-SHA256 under a per-journal key.
Ordering and separators port by accident; **serialization does not, in three
separate ways**, and each was measured against this corpus rather than assumed:

  * dict key order — Python sorts by codepoint, Rust's `BTreeMap` by UTF-8 byte,
    and UTF-8 preserves codepoint order. Safe.
  * list order — sorted by each item's own canonical JSON text, inheriting the
    same property. Safe.
  * `separators` — a compact serializer matches. Safe.
  * **non-ASCII escaping** — `ensure_ascii` renders `é` as `é`; `serde_json`
    emits the character.
  * **non-BMP escaping** — a codepoint above the BMP escapes as a UTF-16
    *surrogate pair*: `\U0001d11e` is written `𝄞`. An implementation
    that escapes non-ASCII but emits one six-digit escape still diverges.
  * **exponent form** — Python writes `1e+22` and `1e-07`; `serde_json` writes
    `1e22` and `1e-7`.

All three produce different bytes, a different sha256, and a fingerprint that no
longer matches the one on disk. The brain's evidence is then fenced out and the
lane re-probes.

A fingerprint mismatch is not a crash and not a corruption, so nothing goes red:
the journal quietly re-enters `checking`. That is why the vectors below carry
their expected `canonical_json` verbatim as well as the digest — a native
implementation that disagrees must fail on the *string*, where the cause is
legible, rather than on a hex digest that says only "different".

⚠ Regenerating this file requires a runnable reference tree. It is a frozen
record, not a live comparison.

Determinism: every value here is a pure function of its input. The HMAC vectors
use a fixed key so the digests are reproducible; the real key is 32 random bytes
per journal and is never recorded anywhere.
"""

