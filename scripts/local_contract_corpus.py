def reference_commit(sources: tuple[str, ...] = REFERENCE_SOURCES) -> str:
    """The commit that last changed the reference this corpus was read from.

    ⚠ Deliberately **not** `HEAD`. A frozen record must be able to name the tree
    it was frozen from, but a fixture whose content moves on every unrelated
    commit cannot be checked for drift — `make check-core-fixtures` compares the
    regenerated bytes exactly, so a `HEAD` stamp turns the regeneration check
    red on the next commit to anything at all.

    Pinning the reference *sources* gets both properties: the value is stable
    while the reference is unchanged, and it moves exactly when the thing this
    corpus describes moves — at which point the check going red is the correct
    answer, because the corpus is stale.
    """
    result = subprocess.run(
        ["git", "log", "-1", "--format=%H", "--", *sources],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    commit = result.stdout.strip()
    if result.returncode != 0 or not commit:
        raise SystemExit(
            "refusing to write a corpus that cannot name its reference tree"
        )
    return commit

# A fixed key so the recorded HMAC digests are reproducible. ⛔ Not a secret and
# ⛔ never a default: the real fingerprint key is 32 bytes from `secrets` written
# to `health/brain-fingerprint.key` on first use, one per journal.
VECTOR_HMAC_KEY = bytes(range(32))


def _vector(name: str, value: Any, note: str) -> dict[str, Any]:
    """Record one canonical-fingerprint case: input, exact text, and digest."""
    canonical = canonical_fingerprint(value)
    return {
        "name": name,
        "note": note,
        # `input_json` is the case's input rendered non-canonically, so a reader
        # reconstructs the input rather than reading it back out of the answer.
        # ⚠ It is JSON, so it cannot express the two input types whose handling
        # this corpus exists to pin — a tuple and a `Path` both arrive already
        # flattened. `input_repr` is the oracle for those: a consumer holding a
        # typed path or a fixed-length sequence must read it, not `input_json`.
        "input_repr": repr(value),
        "input_json": json.dumps(_jsonable(value), ensure_ascii=False, sort_keys=False),
        "canonical_json": canonical,
        "sha256": fingerprint_sha256(canonical),
        "hmac_sha256": hmac.digest(
            VECTOR_HMAC_KEY, canonical.encode("utf-8"), "sha256"
        ).hex(),
    }


def _jsonable(value: Any) -> Any:
    """Render Path values for the input echo; the algorithm does this itself."""
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(item) for item in value]
    if isinstance(value, Path):
        return str(value)
    return value


