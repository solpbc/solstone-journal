def _canonical_digest_vectors() -> list[dict[str, Any]]:
    """`_canonical_digest` wraps its argument in {"value": …} before hashing.

    Recorded separately because the wrapper is invisible at the call site and a
    native implementation that hashes the bare value produces a digest that is
    wrong in a way nothing detects until an SPP provenance block changes.
    """
    cases: list[tuple[str, Any]] = [
        ("null", None),
        ("string", "café"),
        ("block", {"image": "sha256:abc", "measurement": "0" * 96}),
        ("list", [2, 1]),
    ]
    vectors = []
    for name, value in cases:
        payload = canonical_fingerprint({"value": value})
        vectors.append(
            {
                "name": name,
                "input_json": json.dumps(value, ensure_ascii=False),
                "wrapped_canonical_json": payload,
                "hmac_sha256": hmac.digest(
                    VECTOR_HMAC_KEY, payload.encode("utf-8"), "sha256"
                ).hex(),
            }
        )
    return vectors


def _sorted_literal(alias: Any) -> list[str]:
    return sorted(get_args(alias))


