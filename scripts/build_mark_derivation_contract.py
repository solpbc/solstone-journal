"""Build the committed journal mark-derivation contract fixture."""

from __future__ import annotations

import argparse
import json
import sys
import time
import uuid
from pathlib import Path

import argon2.low_level

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from solstone.think.link.mark import _COLORS, _ICON_NAMES, _WORDS, mark_from_jid
from tests.link.test_mark import VECTORS, ReferenceVector

ARTIFACT_PATH = (
    ROOT / "solstone" / "think" / "link" / "mark_assets" / "mark_derivation_contract.json"
)
VECTOR_FIELDS = (
    "name",
    "spki_hex",
    "jid",
    "digest",
    "icon1",
    "color1",
    "color1_hex",
    "icon2",
    "color2",
    "color2_hex",
    "word1",
    "word2",
    "rot1",
    "rot2",
    "raw16",
)


def _digest_hex(jid: uuid.UUID) -> str:
    """Return the independently computed locked Argon2id digest."""
    return argon2.low_level.hash_secret_raw(
        secret=jid.bytes,
        salt=b"solstone-journal-mark-v1",
        time_cost=3,
        memory_cost=65536,
        parallelism=1,
        hash_len=32,
        type=argon2.low_level.Type.ID,
        version=0x13,
    ).hex()


def _derive_vector_record(vector: ReferenceVector) -> dict[str, object]:
    """Derive the mark fields for one recorded jid reference vector."""
    jid = uuid.UUID(vector.jid)
    mark = mark_from_jid(jid)
    return {
        "name": vector.name,
        "spki_hex": vector.spki_hex,
        "jid": str(jid),
        "digest": _digest_hex(jid),
        "icon1": mark.icon1.name,
        "color1": mark.icon1.color_name,
        "color1_hex": mark.icon1.color_hex,
        "icon2": mark.icon2.name,
        "color2": mark.icon2.color_name,
        "color2_hex": mark.icon2.color_hex,
        "word1": mark.words[0],
        "word2": mark.words[1],
        "rot1": mark.icon1.rot,
        "rot2": mark.icon2.rot,
        "raw16": vector.raw16,
    }


def _verify_against_reference(
    vector: ReferenceVector, derived: dict[str, object]
) -> None:
    """Raise on the first difference between a derived record and its oracle."""
    for field in VECTOR_FIELDS:
        expected = getattr(vector, field)
        actual = derived[field]
        if actual != expected:
            raise RuntimeError(
                f"{vector.name}: {field} mismatch: expected {expected!r}, got {actual!r}"
            )


def _verified_reference_vectors() -> list[dict[str, object]]:
    """Derive every reference vector and prove it agrees with the test oracle."""
    records: list[dict[str, object]] = []
    for vector in VECTORS:
        derived = _derive_vector_record(vector)
        _verify_against_reference(vector, derived)
        records.append(derived)
    return records


def _measure_derivation_cost() -> float:
    """Measure one primary-vector mark derivation in seconds."""
    jid = uuid.UUID(VECTORS[0].jid)
    started = time.perf_counter()
    mark_from_jid(jid)
    return round(time.perf_counter() - started, 6)


