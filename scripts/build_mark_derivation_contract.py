def render_contract_json(*, derivation_wall_seconds: float) -> str:
    """Render the canonical contract JSON text."""
    return json.dumps(
        _build_contract_payload(derivation_wall_seconds=derivation_wall_seconds),
        indent=2,
        sort_keys=True,
    ) + "\n"


def write_output() -> None:
    """Measure and write the contract fixture after the vector proof gate passes."""
    rendered = render_contract_json(derivation_wall_seconds=_measure_derivation_cost())
    ARTIFACT_PATH.parent.mkdir(parents=True, exist_ok=True)
    ARTIFACT_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {ARTIFACT_PATH.relative_to(ROOT)}")


def check_output() -> int:
    """Check the fixture without refreshing its non-normative timing observation."""
    try:
        current = ARTIFACT_PATH.read_text(encoding="utf-8")
        payload = json.loads(current)
        seconds = payload["performance_observation"]["seconds"]
    except (FileNotFoundError, json.JSONDecodeError, KeyError, TypeError) as exc:
        print(
            f"Mark derivation contract fixture is missing or malformed: {exc}. "
            "Run: scripts/build_mark_derivation_contract.py",
            file=sys.stderr,
        )
        return 1
    if isinstance(seconds, bool) or not isinstance(seconds, int | float):
        print(
            "Mark derivation contract fixture has a non-numeric "
            "performance_observation.seconds. Run: "
            "scripts/build_mark_derivation_contract.py",
            file=sys.stderr,
        )
        return 1

    expected = render_contract_json(derivation_wall_seconds=float(seconds))
    if current != expected:
        print(
            "Mark derivation contract fixture is stale: "
            f"{ARTIFACT_PATH.relative_to(ROOT)}. Run: "
            "scripts/build_mark_derivation_contract.py",
            file=sys.stderr,
        )
        return 1
    return 0


def main() -> int:
    """Run the fixture writer or staleness check."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check generated contract output without writing it.",
    )
    args = parser.parse_args()
    if args.check:
        return check_output()
    write_output()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
